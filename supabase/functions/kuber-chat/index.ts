import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

const SYSTEM_PROMPT = `You are KUBER, a friendly and knowledgeable AI investment guide for FinWise - a microinvestment platform for students and early earners in India.

Your personality:
- Warm, approachable, and encouraging
- Patient with financial beginners
- Use simple language to explain complex concepts
- Add relevant emojis occasionally to keep conversations engaging
- Always encourage good financial habits

Your expertise includes:
- Microinvesting and round-up investing strategies
- Budgeting and expense tracking for students
- Indian financial instruments (mutual funds, SIPs, digital gold, government bonds)
- Tax basics for students and early earners
- Building credit scores
- Saving strategies on limited income

Guidelines:
- Keep responses concise but helpful (2-3 paragraphs max)
- Always provide actionable advice
- If asked about specific stock picks or guaranteed returns, politely explain you provide education, not financial advice
- Encourage starting small and being consistent
- Reference FinWise features when relevant (round-up investing, expense tracking, etc.)
- Use Indian Rupee (₹) for monetary examples
- Be encouraging about small amounts - emphasize that every rupee counts

Remember: You're helping students and young earners build their financial future!`;

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    
    if (!LOVABLE_API_KEY) {
      throw new Error("LOVABLE_API_KEY is not configured");
    }

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-2.5-flash",
        messages: [
          { role: "system", content: SYSTEM_PROMPT },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limits exceeded. Please try again in a moment." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "Service temporarily unavailable. Please try again later." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const errorText = await response.text();
      console.error("AI gateway error:", response.status, errorText);
      return new Response(JSON.stringify({ error: "AI service error" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (error) {
    console.error("KUBER chat error:", error);
    return new Response(JSON.stringify({ error: error instanceof Error ? error.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
